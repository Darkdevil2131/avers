"""Administrative PostgreSQL migration. Runtime users must never own tables or bypass RLS."""
import os,re
from pathlib import Path
import psycopg

ROOT=Path(__file__).resolve().parents[1]
def schema():
    parts=[]
    for path in sorted((ROOT/'ares/migrations').glob('*.sql')):
        sql=path.read_text()
        sql=re.sub(r'CREATE TRIGGER.*?END;', '',sql,flags=re.S)
        sql=re.sub(r'CREATE VIRTUAL TABLE.*?;', '',sql,flags=re.S)
        sql=sql.replace('INTEGER PRIMARY KEY AUTOINCREMENT','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY').replace(' BLOB ',' BYTEA ')
        sql=re.sub(r'INSERT OR IGNORE (.*?);',lambda m:'INSERT '+m.group(1)+' ON CONFLICT DO NOTHING;',sql,flags=re.S)
        parts.append(sql)
    return '\n'.join(parts)

def migrate(dsn):
    with psycopg.connect(dsn) as db:
        db.execute('''DO $$ BEGIN
          IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='ares_app') THEN CREATE ROLE ares_app LOGIN NOSUPERUSER NOBYPASSRLS; END IF;
          IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='ares_worker') THEN CREATE ROLE ares_worker LOGIN NOSUPERUSER NOBYPASSRLS; END IF;
          END $$;
          ALTER ROLE ares_app NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION;
          ALTER ROLE ares_worker NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE NOREPLICATION;''')
        db.execute(schema())
        db.execute('''CREATE OR REPLACE FUNCTION ares_can_read(pid text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
          SELECT EXISTS(SELECT 1 FROM memberships WHERE project_id=pid AND username=current_setting('ares.user',true))
             OR EXISTS(SELECT 1 FROM projects WHERE id=pid AND owner=current_setting('ares.user',true)) $$;
          CREATE OR REPLACE FUNCTION ares_can_write(pid text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
          SELECT EXISTS(SELECT 1 FROM memberships WHERE project_id=pid AND username=current_setting('ares.user',true) AND role IN ('owner','editor'))
             OR EXISTS(SELECT 1 FROM projects WHERE id=pid AND owner=current_setting('ares.user',true)) $$;
          CREATE OR REPLACE FUNCTION ares_is_owner(pid text) RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path=public,pg_temp AS $$
          SELECT EXISTS(SELECT 1 FROM projects WHERE id=pid AND owner=current_setting('ares.user',true)) $$;
          REVOKE ALL ON FUNCTION ares_can_read(text),ares_can_write(text),ares_is_owner(text) FROM PUBLIC;
          GRANT EXECUTE ON FUNCTION ares_can_read(text),ares_can_write(text),ares_is_owner(text) TO ares_app;
          REVOKE CREATE ON SCHEMA public FROM PUBLIC;
          GRANT USAGE ON SCHEMA public TO ares_app,ares_worker;
          GRANT SELECT,INSERT,UPDATE ON schema_versions,projects,memberships,sources,runs,passages,run_state,audit_events,embeddings,claims,hypotheses,research_memory,feedback,source_details,source_reviews,documents,reports,run_events,evidence_links TO ares_app,ares_worker;
          GRANT USAGE,SELECT ON source_reviews_id_seq,run_events_id_seq,audit_events_id_seq,feedback_id_seq TO ares_app,ares_worker;
          CREATE INDEX IF NOT EXISTS passages_text_gin ON passages USING gin(to_tsvector('english',text));
          CREATE INDEX IF NOT EXISTS passages_project_idx ON passages(project_id);
          CREATE INDEX IF NOT EXISTS sources_project_idx ON sources(project_id);
          CREATE INDEX IF NOT EXISTS run_events_run_idx ON run_events(run_id,id);
          CREATE INDEX IF NOT EXISTS memberships_user_idx ON memberships(username,project_id);''')
        scopes={
          'projects':'id','memberships':'project_id','sources':'project_id','runs':'project_id','passages':'project_id',
          'run_state':'project_id','audit_events':'project_id','embeddings':'project_id','claims':'project_id','hypotheses':'project_id','research_memory':'project_id','feedback':'project_id',
          'source_details':'(SELECT project_id FROM sources WHERE id=source_id)',
          'source_reviews':'(SELECT project_id FROM sources WHERE id=source_id)',
          'documents':'(SELECT project_id FROM sources WHERE id=source_id)',
          'reports':'(SELECT project_id FROM runs WHERE id=run_id)',
          'run_events':'(SELECT project_id FROM runs WHERE id=run_id)',
          'evidence_links':'(SELECT project_id FROM claims WHERE id=claim_id)'}
        from psycopg import sql
        for table,scope in scopes.items():
            name=sql.Identifier(table)
            db.execute(sql.SQL('ALTER TABLE {} ENABLE ROW LEVEL SECURITY').format(name))
            for policy in ('read_scope','insert_scope','update_scope','worker_scope'):
                db.execute(sql.SQL('DROP POLICY IF EXISTS {} ON {}').format(sql.Identifier(policy),name))
            read=f'ares_can_read({scope})'
            write=f'ares_can_write({scope})'
            if table in ('memberships','feedback','audit_events'):write=f'ares_is_owner({scope})' if table!='audit_events' else write
            if table=='projects':write="owner=current_setting('ares.user',true)"
            if table=='audit_events':read=f'ares_is_owner({scope})'
            db.execute(sql.SQL('CREATE POLICY read_scope ON {} FOR SELECT TO ares_app USING ('+read+')').format(name))
            db.execute(sql.SQL('CREATE POLICY insert_scope ON {} FOR INSERT TO ares_app WITH CHECK ('+write+')').format(name))
            db.execute(sql.SQL('CREATE POLICY update_scope ON {} FOR UPDATE TO ares_app USING ('+write+') WITH CHECK ('+write+')').format(name))
            db.execute(sql.SQL('CREATE POLICY worker_scope ON {} TO ares_worker USING (true) WITH CHECK (true)').format(name))
        db.execute('''CREATE OR REPLACE FUNCTION ares_immutable() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'Immutable ARES record'; END $$;''')
        for table in ('sources','runs','reports','source_reviews','run_events','audit_events','claims','evidence_links','hypotheses','documents'):
            name=sql.Identifier(table)
            db.execute(sql.SQL('DROP TRIGGER IF EXISTS immutable ON {}').format(name))
            db.execute(sql.SQL('CREATE TRIGGER immutable BEFORE UPDATE OR DELETE ON {} FOR EACH ROW EXECUTE FUNCTION ares_immutable()').format(name))
        db.execute('REVOKE INSERT,UPDATE ON schema_versions FROM ares_app,ares_worker')
        db.execute('REVOKE INSERT,UPDATE ON memberships,projects FROM ares_worker')

if __name__=='__main__':
    migrate(os.environ['ARES_ADMIN_DATABASE'])
    print('PostgreSQL schema and tenant policies installed. Configure runtime role passwords separately through the host secret manager.')
